"""Generate mermaid diagrams and the reference doc from the definitions."""

from __future__ import annotations

from .validator import next_steps


def _q(text):
    """Quote a label so mermaid treats punctuation as plain text."""
    clean = str(text).replace('"', "'").replace("{", "(").replace("}", ")")
    return f'"{clean}"'


def trigger_label(trigger):
    kind = trigger.get("type")
    if kind == "form_submitted":
        return f"Form submitted: {trigger.get('form')}"
    if kind == "missed_call":
        return "Missed inbound call"
    if kind == "stage_entered":
        return f"Stage entered: {trigger.get('pipeline')}.{trigger.get('stage')}"
    if kind == "tag_added":
        return f"Tag added: {trigger.get('tag')}"
    return str(kind)


def condition_label(cond):
    if "has_tag" in cond:
        return f"has tag {cond['has_tag']}?"
    if "in_stage" in cond:
        return f"in {cond['in_stage']['pipeline']}.{cond['in_stage']['stage']}?"
    if "field" in cond:
        if "equals" in cond:
            return f"{cond['field']} = {cond['equals']}?"
        return f"{cond['field']} is set?"
    return "contact replied?"


def step_label(step):
    kind = step.get("type")
    if kind == "condition":
        return step.get("name") or condition_label(step["if"])
    if step.get("name"):
        return step["name"]
    if kind == "add_tag":
        return f"Add tag: {step['tag']}"
    if kind == "remove_tag":
        return f"Remove tag: {step['tag']}"
    if kind == "set_field":
        value = "today" if step["value"] == "{{today}}" else step["value"]
        return f"Set {step['field']} = {value}"
    if kind == "move_stage":
        return f"Move to {step['pipeline']}.{step['stage']}"
    if kind == "send_sms":
        return f"SMS: {step['id']}"
    if kind == "send_email":
        return f"Email: {step['id']}"
    if kind == "notify_team":
        return f"Notify team: {step['id']}"
    if kind == "create_task":
        return f"Task: {step['title']}"
    if kind == "wait":
        return f"Wait {step['duration']}"
    return "End"


def _node(step):
    node_id = f"s_{step['id']}"  # prefix: "end" is a reserved word in mermaid
    label = _q(step_label(step))
    kind = step.get("type")
    if kind == "condition":
        return f"{node_id}{{{label}}}"
    if kind == "wait":
        return f"{node_id}[/{label}/]"
    if kind == "end":
        return f"{node_id}([{label}])"
    return f"{node_id}[{label}]"


def workflow_diagram(wf):
    steps = wf["steps"]
    lines = ["flowchart TD", f"    trigger(({_q(trigger_label(wf['trigger']))}))"]
    lines += [f"    {_node(step)}" for step in steps]
    lines.append(f"    trigger --> s_{steps[0]['id']}")
    for index, step in enumerate(steps):
        targets = next_steps(step, index, steps)
        if step.get("type") == "condition":
            lines.append(f"    s_{step['id']} -->|yes| s_{targets[0]}")
            lines.append(f"    s_{step['id']} -->|no| s_{targets[1]}")
        else:
            lines += [f"    s_{step['id']} --> s_{t}" for t in targets]
    return "\n".join(lines)


def pipeline_diagram(pipeline):
    stages = pipeline["stages"]
    lines = ["flowchart LR"]
    lines += [f"    {pipeline['id']}_{s['id']}[{_q(s['name'])}]" for s in stages]
    chain = " --> ".join(f"{pipeline['id']}_{s['id']}" for s in stages)
    lines.append(f"    {chain}")
    return "\n".join(lines)


def _fence(diagram):
    return f"```mermaid\n{diagram}\n```"


def render_docs(bp):
    """Build docs/BLUEPRINT.md. Deterministic so CI can check it is current."""
    out = [
        "# Home Services CRM Blueprint",
        "",
        "Generated by `python -m blueprint_tools docs` from the files in `blueprint/`.",
        "Do not edit by hand. This is a documented design in the style of GoHighLevel,",
        "not an official export or import format.",
        "",
        "## Pipelines",
    ]
    for pipeline in bp.pipelines:
        out += ["", f"### {pipeline['name']} (`{pipeline['id']}`)", ""]
        if pipeline.get("description"):
            out += [pipeline["description"], ""]
        out.append(_fence(pipeline_diagram(pipeline)))
    out += ["", "## Custom fields", "", "| Key | Name | Type | Options |", "| --- | --- | --- | --- |"]
    for spec in bp.fields:
        options = ", ".join(str(o) for o in spec.get("options", []))
        out.append(f"| `{spec['key']}` | {spec['name']} | {spec['type']} | {options} |")
    out += ["", "## Tags", "", "| Tag | Purpose |", "| --- | --- |"]
    out += [f"| `{t['name']}` | {t.get('purpose', '')} |" for t in bp.tags]
    out += ["", "## Workflows"]
    for wf in bp.workflows:
        out += [
            "",
            f"### {wf['name']} (`{wf['id']}`)",
            "",
            f"Goal: {wf.get('goal', '')}",
            "",
            f"Source: `blueprint/workflows/{wf.get('_file', wf['id'] + '.yaml')}`",
            "",
            _fence(workflow_diagram(wf)),
        ]
    return "\n".join(out) + "\n"
